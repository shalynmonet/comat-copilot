"""Shipping ticket adapter.

Every approved plan needs paperwork to move with the part -- a work order
and a shipping ticket, per the demo script. In a pilot that's generated by
the carrier's shipping/MRO system; today `MockShippingAdapter` fakes the
same document from the plan's own data, including a dangerous-goods
handling note when the part needs one. `ShippingTicketRequest` in, a
`ShippingTicket` out, either way: a pilot sets `SHIPPING_ADAPTER=<system>`,
registers a real client with the same create_ticket() signature, and
nothing that calls this module changes.
"""

from __future__ import annotations

import os
import random
import string
from dataclasses import dataclass, field
from datetime import datetime
from typing import Optional, Protocol


@dataclass
class ShippingTicketRequest:
    plan_id: int
    option: str
    part_number: str
    part_description: str
    serial: str
    source: Optional[str]
    destination: str
    flight_number: Optional[str]
    is_dangerous_goods: bool


@dataclass
class ShippingTicket:
    ticket_number: str
    work_order_number: str
    created_at: datetime
    source: str  # "mock" | <real system name>
    special_handling: list[str] = field(default_factory=list)
    detail: str = ""


class ShippingAdapter(Protocol):
    def create_ticket(self, request: ShippingTicketRequest) -> ShippingTicket: ...


def _reference(prefix: str, length: int) -> str:
    chars = string.ascii_uppercase + string.digits
    return f"{prefix}-{''.join(random.choices(chars, k=length))}"


class MockShippingAdapter:
    source = "mock"

    def create_ticket(self, request: ShippingTicketRequest) -> ShippingTicket:
        handling = []
        if request.is_dangerous_goods:
            handling.append("DANGEROUS GOODS -- special handling and DG paperwork required")

        route = f"{request.source} -> {request.destination}" if request.source else request.destination
        via = f" via {request.flight_number}" if request.flight_number else ""
        detail = f"{request.option} of {request.part_description} (serial {request.serial}), {route}{via}"

        return ShippingTicket(
            ticket_number=_reference("TCK", 7),
            work_order_number=_reference("WO", 6),
            created_at=datetime.now(),
            source=self.source,
            special_handling=handling,
            detail=detail,
        )


def get_shipping_adapter() -> ShippingAdapter:
    """The pilot swap point: set SHIPPING_ADAPTER=<system> and register a
    class here with the same create_ticket() signature, pointed at real
    credentials. Nothing that calls get_shipping_adapter() has to change."""
    backend = os.environ.get("SHIPPING_ADAPTER", "mock")
    if backend == "mock":
        return MockShippingAdapter()
    raise NotImplementedError(
        f"SHIPPING_ADAPTER={backend!r} isn't wired up yet -- implement a ShippingAdapter "
        "for it and register it in get_shipping_adapter()."
    )
